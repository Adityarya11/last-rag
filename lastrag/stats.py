"""Corpus and QA-set statistics for WixQA. These numbers drive the chunking choices."""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

import numpy as np

from .data import QA_SETS, load_corpus, load_qa

REPORT = Path(__file__).resolve().parent.parent / "reports" / "corpus_stats.md"

# "invoice.In this" / "invoiceEnabling": a lowercase letter or digit followed (optionally
# through . : ! ?) by a capitalised word with no space between them. Approximate, but it
# shows how often the flattened `contents` field glues sentences and list items together.
GLUED = re.compile(r"[a-z0-9][.:!?]?[A-Z][a-z]")


def pct(xs, ps=(10, 50, 90, 99)) -> str:
    xs = np.asarray(xs)
    return (
        " / ".join(str(int(v)) for v in np.percentile(xs, ps))
        + f" (max {int(xs.max())})"
    )


def sections(markdown: str) -> list[str]:
    """Split at ## / ### headings, the natural chunk boundary."""
    parts = re.split(r"\n(?=#{2,3} )", markdown)
    return [p for p in parts if p.strip()]


def main() -> None:
    kb = load_corpus()
    arts = list(kb.values())
    out = [
        "# WixQA corpus statistics",
        "",
        (
            "Generated by `python -m lastrag.stats`. Word counts are whitespace-split "
            "(roughly 1.3 tokens per word for most tokenizers)."
        ),
        "",
        f"## Knowledge base: {len(arts):,} articles",
        "",
        "| article_type | count |",
        "|---|---|",
        *[f"| {t} | {n:,} |" for t, n in Counter(a.type for a in arts).most_common()],
        "",
        "| | p10 / p50 / p90 / p99 |",
        "|---|---|",
        f"| words per article (`contents`) | {pct([len(a.contents.split()) for a in arts])} |",
        f"| words per article (markdown from html) | {pct([len(a.markdown.split()) for a in arts])} |",
        f"| `##`/`###` sections per article | {pct([len(sections(a.markdown)) for a in arts])} |",
        f"| words per section | {pct([len(s.split()) for a in arts for s in sections(a.markdown)])} |",
        "",
        (
            "Glued words (`invoice.In`, `invoiceEnabling`) per article, a measure of how much "
            "the flattened `contents` field runs text together:"
        ),
        "",
        f"- `contents`: {pct([len(GLUED.findall(a.contents)) for a in arts], (50, 90))}",
        f"- markdown: {pct([len(GLUED.findall(a.markdown)) for a in arts], (50, 90))}",
        "",
        "## QA sets",
        "",
        (
            "| set | queries | gold articles / query (1/2/3+) | question words p50 | "
            "gold article words p50 / p90 | gold article types |"
        ),
        "|---|---|---|---|---|---|",
    ]
    for name in QA_SETS:
        qa = load_qa(name)
        n_gold = Counter(min(len(q.gold), 3) for q in qa)
        gold = [kb[g] for q in qa for g in q.gold]
        gw = np.array([len(a.markdown.split()) for a in gold])
        types = ", ".join(
            f"{t} {n}" for t, n in Counter(a.type for a in gold).most_common()
        )
        out.append(
            f"| {name} | {len(qa):,} | {n_gold[1]} / {n_gold[2]} / {n_gold[3]} | "
            f"{int(np.median([len(q.question.split()) for q in qa]))} | "
            f"{int(np.median(gw))} / {int(np.percentile(gw, 90))} | {types} |"
        )
    text = "\n".join(out) + "\n"
    print(text)
    REPORT.parent.mkdir(exist_ok=True)
    REPORT.write_text(text, encoding="utf-8")
    print(f"wrote {REPORT}")


if __name__ == "__main__":
    main()
